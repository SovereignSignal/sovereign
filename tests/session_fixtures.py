"""Synthetic Claude Code homes, transcripts and a loopback model for the session tests.

Nothing here is copied from a real session. `transcript` writes every line kind a real
file carries, and plants one marker in each kind the reader must drop, so a test can
prove the boundary by searching the excerpt for `MARK-`. Key-shaped values are built by
concatenation so this file never carries one whole.
"""
import http.server
import json
import os
from pathlib import Path
import subprocess
import sys
import threading
import time

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "lib"))
import brain_local  # noqa: E402

# One marker per line kind the excerpt must never carry.
MARKERS = (
    "MARK-HOOK",      # attachment hook_success (the archive's own session-start pack)
    "MARK-CONTEXT",   # attachment hook_additional_context
    "MARK-THINK",     # assistant thinking block
    "MARK-TOOLIN",    # assistant tool_use input
    "MARK-RESULT",    # user tool_result line (toolUseResult)
    "MARK-SYSTEM",    # system line
    "MARK-BLOB",      # api-request-blob
    "MARK-SNAP",      # file-history-snapshot
    "MARK-QUEUE",     # queue-operation
    "MARK-REQUEST",   # api-request
    "MARK-META",      # user line with isMeta
    "MARK-REMINDER",  # user text opening with <system-reminder>
    "MARK-COMMAND",   # user text opening with <command-
    "MARK-LOCAL",     # user text opening with <local-command-
    "MARK-NOTIFY",    # task notification (origin.kind is not human)
    "MARK-BASH",      # <bash-stdout> echoed into a user line
    "MARK-COMPACT",   # compaction summary
    "MARK-SUB",       # a subagent transcript one level down
)

# Credential-shaped values the excerpt's clean step must remove.
KEYS = (
    "gh" + "p_" + "A" * 36,
    "sk-" + "ant-" + "api03-" + "Q7x" * 12,
    "AK" + "IA" + "Z" * 16,
    "xo" + "xb-" + "1234567890" + "-" + "abcdefghijKL",
)


def make_home(tmp):
    """A temp HOME with an empty projects tree, an archive made by brain_local.create,
    and a state directory. Returns (home, vault, state) as resolved Paths."""
    tmp = Path(tmp)
    home = tmp / "home"
    (home / ".claude" / "projects").mkdir(parents=True)
    vault = Path(brain_local.create(tmp / "archive", ROOT)["root"])
    state = tmp / "state"
    state.mkdir()
    return home.resolve(), vault, state.resolve()


def _iso(epoch):
    return time.strftime("%Y-%m-%dT%H:%M:%S.000Z", time.gmtime(epoch))


def transcript(home, key, sid, cwd, prompts, entrypoint="cli", sidechain=False, age_s=3600,
               assistant="Done.", extra_cwds=()):
    """Write ~/.claude/projects/<key>/<sid>.jsonl: one typed prompt per entry of
    `prompts`, each answered by a tool call and `assistant`, plus one line of every
    dropped kind with its marker. The last line is dated `age_s` ago and so is the
    file's mtime. Each of `extra_cwds` appears on its own line after the first turn.
    A subagent transcript and a tool result sit one level down, as in a real tree.
    Returns the transcript path as a str."""
    folder = Path(home) / ".claude" / "projects" / key
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / (sid + ".jsonl")
    end = time.time() - age_s
    count = [0]
    lines = []
    steps = 8 * max(1, len(prompts)) + 30
    start = end - steps

    def base(kind, where=None):
        count[0] += 1
        return {"type": kind, "sessionId": sid, "uuid": "u-%d" % count[0], "cwd": where or str(cwd),
                "timestamp": _iso(start + count[0]), "entrypoint": entrypoint,
                "isSidechain": bool(sidechain), "userType": "external", "version": "2.0.0"}

    def user(content, **extra):
        line = base("user")
        line["message"] = {"role": "user", "content": content}
        line.update(extra)
        lines.append(line)

    def assistant_blocks(blocks):
        line = base("assistant")
        line["message"] = {"role": "assistant", "content": blocks}
        lines.append(line)

    def attachment(kind, content, where=None):
        line = base("attachment", where)
        line["attachment"] = {"type": kind, "content": content, "hookName": "SessionStart"}
        lines.append(line)

    lines.append({"type": "file-history-snapshot", "messageId": "m0",
                  "snapshot": {"trackedFileBackups": {"MARK-SNAP": {}}}, "isSnapshotUpdate": False})
    attachment("hook_success", "MARK-HOOK the session-start pack")
    attachment("hook_additional_context", "MARK-CONTEXT added by a hook")
    user("Caveat: MARK-META generated by the harness", isMeta=True)
    user("<command-name>/clear</command-name> MARK-COMMAND")
    user("<local-command-stdout>MARK-LOCAL</local-command-stdout>")
    user([{"type": "text", "text": "<system-reminder>MARK-REMINDER</system-reminder>"}])
    for i, prompt in enumerate(prompts):
        user(prompt, origin={"kind": "human"})
        tid = "toolu_%s_%d" % (sid[:6], i)
        if i == 0:
            assistant_blocks([{"type": "thinking", "thinking": "MARK-THINK private reasoning", "signature": "s"}])
        assistant_blocks([{"type": "tool_use", "id": tid, "name": "Edit",
                           "input": {"file_path": "notes.md", "old_string": "MARK-TOOLIN", "new_string": "x"}}])
        user([{"type": "tool_result", "tool_use_id": tid, "content": "MARK-RESULT output"}],
             toolUseResult={"stdout": "MARK-RESULT output"})
        if i == 0:
            assistant_blocks([{"type": "text", "text": "Noted the values " + " ".join(KEYS)}])
            lines.append({"type": "api-request", "sessionId": sid, "id": "r1", "timestamp": _iso(start + count[0]),
                          "params": {"note": "MARK-REQUEST"}})
            lines.append({"type": "api-request-blob", "sessionId": sid, "hash": "h1",
                          "message": {"role": "user", "content": [{"type": "text", "text": "MARK-BLOB copy"}]}})
            lines.append({"type": "queue-operation", "sessionId": sid, "operation": "enqueue",
                          "timestamp": _iso(start + count[0]), "content": "MARK-QUEUE queued prompt"})
            system = base("system")
            system.update({"subtype": "informational", "content": "MARK-SYSTEM notice", "level": "info"})
            lines.append(system)
            user("<task-notification>MARK-NOTIFY finished</task-notification>",
                 origin={"kind": "task-notification", "producer": "bash"})
            user("<bash-stdout>MARK-BASH</bash-stdout><bash-stderr></bash-stderr>")
            user("Summary of the earlier conversation: MARK-COMPACT", isCompactSummary=True,
                 isVisibleInTranscriptOnly=True)
            for extra in extra_cwds:
                attachment("date", "today", where=str(extra))
        assistant_blocks([{"type": "text", "text": assistant}])
    lines.append({"type": "ai-title", "sessionId": sid, "aiTitle": "Synthetic session"})
    lines[-2]["timestamp"] = _iso(end)
    with open(path, "w") as fh:
        for line in lines:
            fh.write(json.dumps(line) + "\n")
    os.utime(path, (end, end))

    sub = folder / sid / "subagents"
    sub.mkdir(parents=True, exist_ok=True)
    agent = dict(base("user"), isSidechain=True, message={"role": "user", "content": "MARK-SUB subagent prompt"})
    (sub / "agent-a1.jsonl").write_text(json.dumps(agent) + "\n")
    results = folder / sid / "tool-results"
    results.mkdir(parents=True, exist_ok=True)
    (results / "r1.jsonl").write_text(json.dumps(dict(agent, message={"role": "user", "content": "MARK-SUB"})) + "\n")
    return str(path)


class ModelStub:
    """A loopback model endpoint. `reply_fn(body)` gets each request body and returns
    the reply text, an int HTTP status to fail with, or (status, text). OpenAI-style
    requests get a chat completion, `/v1/messages` gets the Messages API shape.
    `.url` is the chat completions URL, `.requests` the bodies seen, `.calls` their count."""

    def __init__(self, reply_fn=None):
        self.requests = []
        self.paths = []
        self.reply_fn = reply_fn or (lambda body: '{"captures": []}')
        stub = self

        class Handler(http.server.BaseHTTPRequestHandler):
            def log_message(self, *a):
                pass

            def do_POST(self):
                raw = self.rfile.read(int(self.headers.get("Content-Length") or 0))
                try:
                    body = json.loads(raw or b"{}")
                except ValueError:
                    body = {"unparsed": raw.decode("utf-8", "replace")}
                stub.requests.append(body)
                stub.paths.append(self.path)
                reply = stub.reply_fn(body)
                status, text = 200, reply
                if isinstance(reply, int):
                    status, text = reply, ""
                elif isinstance(reply, tuple):
                    status, text = reply
                if status != 200:
                    out = json.dumps({"error": {"message": "stub status %d" % status}}).encode()
                elif self.path.rstrip("/").endswith("/messages"):
                    out = json.dumps({"stop_reason": "end_turn",
                                      "content": [{"type": "text", "text": text}]}).encode()
                else:
                    out = json.dumps({"choices": [{"message": {"content": text}}]}).encode()
                self.send_response(status)
                self.send_header("Content-Type", "application/json")
                self.send_header("Content-Length", str(len(out)))
                self.end_headers()
                self.wfile.write(out)

        self.server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        threading.Thread(target=self.server.serve_forever, daemon=True).start()
        self.base = "http://127.0.0.1:%d" % self.server.server_address[1]
        self.url = self.base + "/v1/chat/completions"

    @property
    def calls(self):
        return len(self.requests)

    def close(self):
        self.server.shutdown()
        self.server.server_close()

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        self.close()


SESSIONS_SH = ROOT / "connectors" / "harness" / "claude-code" / "sessions.sh"
LANE = "claude-code-testhost"
PROMPTS = ("Remember that every archive copy stays encrypted from now on.",
           "We decided to switch to the staging copy for tests.",
           "Thanks, that is all.")


def iso_minute(epoch):
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(epoch))


class Rig:
    """One machine for a session tick through sessions.sh: a temp HOME and archive, a
    hub.json naming a loopback ModelStub (so the archive's own model is the stub),
    capture switched on a day ago, and the temp root allow-listed so a synthetic
    project under $TMPDIR is not refused as temporary. `cfg` overrides config keys."""

    def __init__(self, tmp, reply_fn=None, enabled=True, **cfg):
        self.tmp = Path(tmp).resolve()
        self.home, self.vault, self.state = make_home(self.tmp)
        self.proj = self.tmp / "work" / "proj"
        self.proj.mkdir(parents=True)
        self.stub = ModelStub(reply_fn)
        self.hub_json(self.stub.url)
        config = {"version": 1, "allow": [str(self.tmp)],
                  "tools": {"claude-code": {"enabled": enabled, "enabled_at": iso_minute(time.time() - 86400)}}}
        config.update(cfg)
        (self.state / "session-capture.json").write_text(json.dumps(config))
        self.lane = self.vault / "raw" / "tools" / LANE
        self.sessions = self.lane / "sessions"

    def hub_json(self, endpoint, model="qwen-test:8b"):
        (self.state / "hub.json").write_text(json.dumps(
            {"vault": str(self.vault), "lane": "curator", "model": model, "endpoint": endpoint}))

    def env(self, **extra):
        e = {"HOME": str(self.home), "PATH": "/usr/bin:/bin:/usr/sbin:/sbin", "SOV_STATE_DIR": str(self.state),
             "BRAIN_ROOT": str(self.vault), "BRAIN_HOST": "testhost", "SOV_PYTHON": sys.executable,
             "TMPDIR": os.environ.get("TMPDIR", "/tmp"), "PYTHONDONTWRITEBYTECODE": "1"}
        e.update(extra)
        return {k: v for k, v in e.items() if v is not None}

    def transcript(self, sid, prompts=PROMPTS, cwd=None, **kw):
        return transcript(self.home, "-work-proj", sid, cwd or self.proj, list(prompts), **kw)

    def tick(self, **extra):
        # The publish is rsync's quick check (size and whole-second mtime): two ticks in one
        # second can write manifests of one size, and the second would not be carried.
        wait = getattr(self, "_last_tick", 0) + 1.1 - time.time()
        if wait > 0:
            time.sleep(wait)
        self._last_tick = time.time()
        return subprocess.run(["/bin/bash", str(SESSIONS_SH)], capture_output=True, text=True,
                              env=self.env(**extra), timeout=240)

    def tick_here(self, **extra):
        """run.tick in this process, then commit or discard as sessions.sh would, with no
        publish: for cases that patch the module (a missing sov-capture, short timeouts).
        The tick's private stage is <tmp>/private/stage; returns the tick's summary."""
        from unittest import mock
        from session_ingest import run
        dest = self.tmp / "private" / "stage" / "raw" / "tools" / LANE / "sessions"
        dest.mkdir(parents=True, exist_ok=True)
        env = self.env(**extra)
        with mock.patch.dict(os.environ, env, clear=True):
            summary = run.tick("claude-code", env, str(dest), time.time())
            (run.commit if summary["exit"] == 0 else run.discard)("claude-code", env)
        self.private = dest
        return summary

    def watermark(self):
        path = self.state / "sessions" / "claude-code.json"
        return json.loads(path.read_text()) if path.exists() else {"sessions": {}, "waiting": None}

    def verdict(self, sid):
        return (self.watermark()["sessions"].get(sid) or {}).get("verdict")

    def captures(self):
        if not self.sessions.is_dir():
            return []
        return sorted(p for p in self.sessions.glob("*.md") if p.name != "MANIFEST.md")

    def manifest(self):
        return (self.sessions / "MANIFEST.md").read_text()

    def close(self):
        self.stub.close()
